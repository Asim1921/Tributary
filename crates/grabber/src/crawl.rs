//! Exploring: one page at a time, remembering where it's got to.

use std::collections::{BTreeMap, HashSet, VecDeque};
use std::fs;
use std::future::Future;
use std::path::{Path, PathBuf};
use std::time::Duration;

use serde::{Deserialize, Serialize};
use tokio_util::sync::CancellationToken;
use url::{Position, Url};

use crate::ROBOT_NAME;
use crate::links::{self, Link, LinkKind};
use crate::offline;
use crate::project::{Project, extension_of};
use crate::robots::Robots;

/// The shortest wait between requests, whatever a project asks for.
const MIN_DELAY: Duration = Duration::from_millis(100);

/// Longer addresses are almost always generated by a trap.
const MAX_ADDRESS_CHARS: usize = 2000;

/// The most files one project lists.
const MAX_FILES: usize = 100_000;

/// The most stylesheets one project reads. They don't count as pages, because a page
/// isn't readable without them, so they need a limit of their own.
const MAX_STYLESHEETS: usize = 2000;

/// What a page is built from, which only matters when saving the page itself.
const PAGE_PARTS: [&str; 3] = ["js", "mjs", "css"];

/// Extensions that mean a page rather than a file to save.
const PAGE_EXTENSIONS: [&str; 11] = [
    "html", "htm", "xhtml", "shtml", "php", "asp", "aspx", "jsp", "cfm", "cgi", "pl",
];

/// A page waiting to be read.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Target {
    pub url: String,
    pub depth: u32,
    /// A stylesheet to read, rather than a page.
    pub style: bool,
    pub from: String,
}

/// A file that exploring turned up.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct Found {
    pub url: String,
    /// The page that linked to it.
    pub from: String,
    pub size: Option<u64>,
}

/// A page saved to read with no connection.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct SavedPage {
    pub url: String,
    /// Relative to the project's folder.
    pub path: PathBuf,
    pub style: bool,
}

/// How far exploring has got. It's a plain value, so it can be saved and picked up again.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct Crawl {
    queue: VecDeque<Target>,
    seen: HashSet<String>,
    /// What's known of each site's `robots.txt`.
    robots: BTreeMap<String, Robots>,
    /// Addresses that redirected, and where they ended up.
    moved: BTreeMap<String, String>,
    pub found: Vec<Found>,
    pub saved_pages: Vec<SavedPage>,
    pub pages_read: usize,
    styles_read: usize,
    pub pages_failed: usize,
    /// Pages left alone because `robots.txt` asked.
    pub pages_refused: usize,
    /// Set once there's nothing left to explore.
    pub finished: bool,
}

/// What a server gave for a page.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Fetched {
    /// Where it really came from, after any redirects.
    pub url: String,
    pub found: bool,
    pub content_type: Option<String>,
    /// Empty if it wasn't text.
    pub text: Option<String>,
}

/// Where pages come from.
pub trait Source {
    fn fetch(&self, url: &str) -> impl Future<Output = Result<Fetched, String>> + Send;

    /// The size of a file, if the server says.
    fn size(&self, url: &str) -> impl Future<Output = Option<u64>> + Send;
}

/// How a run of exploring ended.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Ended {
    Finished,
    Stopped,
}

fn is_page_part(url: &Url) -> bool {
    extension_of(url).is_some_and(|extension| PAGE_PARTS.contains(&extension.as_str()))
}

/// True for an address that's plainly a file rather than a page.
fn looks_like_file(url: &Url) -> bool {
    extension_of(url).is_some_and(|extension| !PAGE_EXTENSIONS.contains(&extension.as_str()))
}

fn is_html(content_type: Option<&str>) -> bool {
    content_type.is_none_or(|kind| {
        let kind = kind.to_ascii_lowercase();
        kind.starts_with("text/html") || kind.contains("xhtml")
    })
}

fn origin_of(url: &Url) -> String {
    url[..Position::BeforePath].to_owned()
}

impl Crawl {
    /// Starts exploring from a project's first page.
    pub fn start(project: &Project) -> Self {
        let mut crawl = Self::default();
        let start = project.start_url.trim().to_owned();
        crawl.seen.insert(start.clone());
        crawl.queue.push_back(Target {
            url: start.clone(),
            depth: 0,
            style: false,
            from: start,
        });
        crawl
    }

    pub fn pages_waiting(&self) -> usize {
        self.queue.len()
    }

    fn allowed(&self, url: &Url) -> bool {
        let Some(rules) = self.robots.get(&origin_of(url)) else {
            return true;
        };
        rules.allows(&url[Position::BeforePath..Position::AfterQuery])
    }

    /// Adds a file someone could choose to fetch, if it's within reach.
    fn add_file(&mut self, project: &Project, url: &Url, from: &str) {
        if project.files_anywhere || project.in_scope(url) {
            self.list_file(project, url, from);
        }
    }

    fn list_file(&mut self, project: &Project, url: &Url, from: &str) {
        if !project.wants_file(url) || !self.allowed(url) {
            return;
        }
        if self.found.len() < MAX_FILES && self.seen.insert(url.to_string()) {
            self.found.push(Found {
                url: url.to_string(),
                from: from.to_owned(),
                size: None,
            });
        }
    }

    fn add_page(&mut self, project: &Project, url: &Url, depth: u32, from: &str) {
        let waiting = self.queue.iter().filter(|target| !target.style).count();
        let room = self.pages_read + waiting < project.page_limit();
        if depth > project.max_depth || !project.wants_page(url) {
            return;
        }
        if room && project.in_scope(url) && self.seen.insert(url.to_string()) {
            self.queue.push_back(Target {
                url: url.to_string(),
                depth,
                style: false,
                from: from.to_owned(),
            });
        }
    }

    /// Adds a stylesheet to read. A saved page needs its stylesheets, wherever they're
    /// kept, so they don't use up the page limit or have to be on the same site.
    fn add_style(&mut self, url: &Url, depth: u32, from: &str) {
        if self.styles_read < MAX_STYLESHEETS && self.seen.insert(url.to_string()) {
            self.queue.push_back(Target {
                url: url.to_string(),
                depth,
                style: true,
                from: from.to_owned(),
            });
        }
    }

    fn consider(&mut self, project: &Project, link: &Link, depth: u32, from: &str) {
        if link.url.as_str().len() > MAX_ADDRESS_CHARS {
            return;
        }

        match link.kind {
            LinkKind::Follow if looks_like_file(&link.url) => {
                self.add_file(project, &link.url, from);
            }
            LinkKind::Follow => self.add_page(project, &link.url, depth, from),
            // What a page is built from is needed wherever it's kept, as it would be by a
            // browser. Nothing is explored there, and files merely linked to stay out.
            LinkKind::Asset if project.offline => self.list_file(project, &link.url, from),
            LinkKind::Asset if looks_like_file(&link.url) && !is_page_part(&link.url) => {
                self.add_file(project, &link.url, from);
            }
            LinkKind::Asset => {}
            LinkKind::Style if project.offline => self.add_style(&link.url, depth, from),
            LinkKind::Style => {}
        }
    }

    /// Takes in what a server gave for a page. Returns its text if it should be saved.
    fn read(&mut self, project: &Project, target: &Target, page: Fetched) -> Option<String> {
        if !page.found {
            self.pages_failed += 1;
            return None;
        }
        let Ok(url) = Url::parse(&page.url) else {
            self.pages_failed += 1;
            return None;
        };

        // Being redirected off the site doesn't widen where exploring may go.
        if url.as_str() != target.url {
            if !target.style && !project.in_scope(&url) {
                return None;
            }
            self.moved.insert(target.url.clone(), url.to_string());
            if !self.seen.insert(url.to_string()) {
                return None;
            }
        }

        if target.style {
            self.styles_read += 1;
            let text = page.text?;
            for link in links::css_links(&text, &url) {
                self.consider(project, &link, target.depth, &target.url);
            }
            return Some(text);
        }

        // A link with no extension can turn out to be a file.
        if !is_html(page.content_type.as_deref()) || page.text.is_none() {
            self.seen.remove(url.as_str());
            self.add_file(project, &url, &target.from);
            return None;
        }

        self.pages_read += 1;
        let text = page.text?;
        for link in links::page_links(&text, &url) {
            self.consider(project, &link, target.depth + 1, url.as_str());
        }
        project.offline.then_some(text)
    }

    /// The local copy of an address, if it has one, as a link from `from`.
    fn saved_link(&self, from: &Path, url: &Url) -> Option<String> {
        let address = url.as_str();
        let address = self.moved.get(address).map_or(address, String::as_str);

        if let Some(page) = self.saved_pages.iter().find(|page| page.url == address) {
            return Some(offline::relative_link(from, &page.path));
        }
        self.found
            .iter()
            .any(|file| file.url == address)
            .then(|| offline::relative_link(from, &offline::local_path(url, false)))
    }
}

/// Saves a page's text under the project's folder.
fn save_page(project: &Project, crawl: &mut Crawl, url: &str, style: bool, text: &str) {
    let Ok(address) = Url::parse(url) else {
        return;
    };
    let local = offline::local_path(&address, !style);
    let path = project.folder.join(&local);

    let written = path
        .parent()
        .map_or(Ok(()), fs::create_dir_all)
        .and_then(|()| fs::write(&path, text));
    if written.is_ok() {
        crawl.saved_pages.push(SavedPage {
            url: url.to_owned(),
            path: local,
            style,
        });
    }
}

/// Points every saved page's links at the saved copies, once all of them are known.
fn rewrite_saved_pages(project: &Project, crawl: &Crawl) {
    // Two addresses can share a file, such as `/` and `/index.html`. Each file is only
    // done once, because a link that's already local would be read as a web address.
    let mut done = HashSet::new();

    for page in &crawl.saved_pages {
        if !done.insert(&page.path) {
            continue;
        }

        let path = project.folder.join(&page.path);
        let (Ok(text), Ok(url)) = (fs::read_to_string(&path), Url::parse(&page.url)) else {
            continue;
        };

        let link = |target: &Url| crawl.saved_link(&page.path, target);
        let rewritten = if page.style {
            offline::rewrite_css(&text, &url, &link)
        } else {
            offline::rewrite_html(&text, &url, &link)
        };
        // One page that can't be updated shouldn't lose the rest of the site.
        let _ = fs::write(&path, rewritten);
    }
}

/// Learns a site's rules. Missing rules mean anything goes, but a site that's in trouble
/// is left alone until it can say what it wants, as RFC 9309 asks.
async fn learn_robots<S: Source>(crawl: &mut Crawl, source: &S, origin: &str) {
    let address = format!("{origin}/robots.txt");
    let rules = match source.fetch(&address).await {
        Ok(page) if page.found => {
            Robots::parse(page.text.as_deref().unwrap_or_default(), ROBOT_NAME)
        }
        Ok(_) => Robots::default(),
        Err(_) => Robots::deny_all(),
    };
    crawl.robots.insert(origin.to_owned(), rules);
}

/// Waits, returning false if stopped meanwhile.
async fn pause(delay: Duration, stop: &CancellationToken) -> bool {
    tokio::select! {
        () = stop.cancelled() => false,
        () = tokio::time::sleep(delay) => true,
    }
}

/// Works out the sizes of the files found, dropping any outside the project's limits.
async fn apply_size_limits<S: Source>(
    project: &Project,
    crawl: &mut Crawl,
    source: &S,
    delay: Duration,
    stop: &CancellationToken,
) -> Ended {
    if project.min_size.is_none() && project.max_size.is_none() {
        return Ended::Finished;
    }

    let mut index = 0;
    while index < crawl.found.len() {
        if crawl.found[index].size.is_none() {
            if !pause(delay, stop).await {
                return Ended::Stopped;
            }
            crawl.found[index].size = source.size(&crawl.found[index].url).await;
        }

        // A file that won't say its size is kept, because it may well be wanted.
        if crawl.found[index]
            .size
            .is_some_and(|size| !project.wants_size(size))
        {
            crawl.found.remove(index);
        } else {
            index += 1;
        }
    }
    Ended::Finished
}

/// Explores until there's nothing left or it's stopped. `report` hears after each page.
/// Stopped exploring can carry on later from the same `crawl`.
pub async fn explore<S: Source>(
    project: &Project,
    crawl: &mut Crawl,
    source: &S,
    stop: &CancellationToken,
    mut report: impl FnMut(&Crawl),
) -> Ended {
    let base_delay = Duration::from_millis(project.delay_ms).max(MIN_DELAY);

    while let Some(target) = crawl.queue.pop_front() {
        let Ok(url) = Url::parse(&target.url) else {
            crawl.pages_failed += 1;
            continue;
        };

        let origin = origin_of(&url);
        if !crawl.robots.contains_key(&origin) {
            learn_robots(crawl, source, &origin).await;
        }
        if !crawl.allowed(&url) {
            crawl.pages_refused += 1;
            report(crawl);
            continue;
        }

        let delay = crawl
            .robots
            .get(&origin)
            .and_then(Robots::delay)
            .map_or(base_delay, |asked| asked.max(base_delay));

        if !pause(delay, stop).await {
            crawl.queue.push_front(target);
            return Ended::Stopped;
        }

        match source.fetch(&target.url).await {
            Ok(page) => {
                let saved_at = page.url.clone();
                if let Some(text) = crawl.read(project, &target, page) {
                    save_page(project, crawl, &saved_at, target.style, &text);
                }
            }
            Err(_) => crawl.pages_failed += 1,
        }
        report(crawl);
    }

    if apply_size_limits(project, crawl, source, base_delay, stop).await == Ended::Stopped {
        return Ended::Stopped;
    }

    if project.offline {
        rewrite_saved_pages(project, crawl);
    }
    crawl.finished = true;
    report(crawl);
    Ended::Finished
}
